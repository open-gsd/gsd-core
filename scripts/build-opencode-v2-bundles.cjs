const BUNDLES = Object.freeze([
  Object.freeze({ entry: 'src/opencode-v2-plugin/index.cjs', outfile: '.opencode/plugins/gsd-core.js', format: 'cjs', sourcemap: false, embeddedNotice: true }),
  Object.freeze({ entry: 'src/opencode-v2-attestation.cts', outfile: 'gsd-core/bin/lib/opencode-v2-attestation.cjs', format: 'cjs', sourcemap: 'linked', notice: 'gsd-core/bin/lib/opencode-v2-attestation.THIRD_PARTY_NOTICES.txt' }),
]);
const BUNDLE_PRODUCER = 'opencode-v2-bundles';

function repositoryOutputPath(value, label) {
  assert.equal(typeof value, 'string', `${label} must be a string`);
  assert.ok(value.length > 0, `${label} must not be empty`);
  assert.equal(path.isAbsolute(value), false, `${label} must be repository-relative: ${value}`);
  assert.equal(value.includes('\\'), false, `${label} must use forward slashes: ${value}`);
  const normalized = path.posix.normalize(value);
  assert.equal(normalized, value, `${label} must be normalized: ${value}`);
  assert.notEqual(normalized, '.', `${label} must name a file`);
  assert.notEqual(normalized, '..', `${label} must stay inside the repository`);
  assert.equal(normalized.startsWith('../'), false, `${label} must stay inside the repository`);
  return normalized;
}

function getBundleArtifactManifest(bundles = BUNDLES) {
  const outputs = new Set();
  const entries = new Set();
  const add = (value, label) => {
    const output = repositoryOutputPath(value, label);
    assert.equal(outputs.has(output), false, `duplicate bundle output: ${output}`);
    outputs.add(output);
  };
  for (const [index, bundle] of bundles.entries()) {
    assert.ok(bundle && typeof bundle === 'object', `bundle[${index}] must be an object`);
    const entry = repositoryOutputPath(bundle.entry, `bundle[${index}].entry`);
    assert.equal(entries.has(entry), false, `duplicate bundle entry: ${entry}`);
    entries.add(entry);
    add(bundle.outfile, `bundle[${index}].outfile`);
    if (bundle.sourcemap === 'linked') add(`${bundle.outfile}.map`, `bundle[${index}].sourcemap`);
    if (bundle.notice) add(bundle.notice, `bundle[${index}].notice`);
  }
  for (const entry of entries) assert.equal(outputs.has(entry), false, `bundle source/output collision: ${entry}`);
  return Object.freeze({ producer: BUNDLE_PRODUCER, outputs: Object.freeze([...outputs].sort()) });
}

function packageName(input) {
  const marker = 'node_modules/';
  const index = input.lastIndexOf(marker);
  if (index < 0) return undefined;
  const segments = input.slice(index + marker.length).split('/');
  return segments[0].startsWith('@') ? `${segments[0]}/${segments[1]}` : segments[0];
}
function packageMetadata(name) {
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', ...name.split('/'), 'package.json'), 'utf8'));
  assert.equal(manifest.license, 'MIT', `bundled dependency ${name} needs an explicit license renderer`);
  assert.match(name, /^@opencode\//, `unexpected bundled dependency ${name} needs a reviewed notice`);
  return { name, version: manifest.version, repository: manifest.repository?.url || 'https://github.com/anomalyco/opencode' };
}
function renderNotice(names) {
  const packages = [...names].sort().map(packageMetadata);
  return ['Third-Party Notices for the generated OpenCode V2 runtime bundle', '', ...packages.map((item) => `${item.name}@${item.version} — MIT — ${item.repository}`), '', 'The packages above are distributed under the following license:', '', MIT_LICENSE].join('\n');
}
function renderEmbeddedNotice(names) { return `/*\n${renderNotice(names).replaceAll('*/', '* /')}\n*/\n`; }
function compareOrWrite(relative, bytes, check) {
  const target = path.join(ROOT, relative);
  const expected = Buffer.from(bytes);
  if (check) {
    assert.ok(fs.existsSync(target), `missing generated OpenCode V2 artifact: ${relative}`);
    assert.deepEqual(fs.readFileSync(target), expected, `generated OpenCode V2 artifact drift: ${relative}`);
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, expected);
}
function bundledPackageNames(metafile) {
  const names = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const name = packageName(input);
    if (name) names.add(name);
  }
  return names;
}
function assertNoOpenCodeRuntimeImports(bytes, outfile) {
  const output = Buffer.from(bytes).toString('utf8');
  assert.doesNotMatch(output, /\brequire\(\s*["']@opencode\//, `${outfile} must bundle @opencode dependencies`);
  assert.doesNotMatch(output, /\bimport\(\s*["']@opencode\//, `${outfile} must bundle @opencode dependencies`);
}

async function main(argv = process.argv.slice(2)) {
  const check = argv.includes('--check');
  assert.deepEqual(argv.filter((value) => value !== '--check'), [], 'unsupported argument');
  const artifactManifest = getBundleArtifactManifest();
  const declaredOutputs = new Set(artifactManifest.outputs);
  const producedOutputs = new Set();
  for (const bundle of BUNDLES) {
    const result = await esbuild.build({
      absWorkingDir: ROOT, entryPoints: [bundle.entry], outfile: path.join(ROOT, bundle.outfile), bundle: true,
      platform: 'node', format: bundle.format, target: 'node24', sourcemap: bundle.sourcemap, sourcesContent: false,
      legalComments: 'none', banner: { js: GENERATED_BANNER.trimEnd() },
      // CJS always selects the __dirname branch; this replacement prevents
      // esbuild from lowering the source-only ESM fallback to an empty object.
      define: { 'import.meta.url': JSON.stringify('file:///unused-in-cjs-bundle') },
      metafile: true, write: false,
    });
    const names = bundledPackageNames(result.metafile);
    for (const output of result.outputFiles) {
      const relative = path.relative(ROOT, output.path).split(path.sep).join('/');
      assert.ok(declaredOutputs.has(relative), `undeclared OpenCode V2 bundle output: ${relative}`);
      assert.equal(producedOutputs.has(relative), false, `duplicate OpenCode V2 bundle output: ${relative}`);
      producedOutputs.add(relative);
      const contents = bundle.embeddedNotice ? Buffer.concat([Buffer.from(renderEmbeddedNotice(names)), output.contents]) : output.contents;
      if (bundle.embeddedNotice) assertNoOpenCodeRuntimeImports(contents, relative);
      compareOrWrite(relative, contents, check);
    }
    if (bundle.notice) {
      assert.ok(names.size > 0, `notice has no bundled dependencies: ${bundle.notice}`);
      assert.ok(declaredOutputs.has(bundle.notice), `undeclared OpenCode V2 notice output: ${bundle.notice}`);
      assert.equal(producedOutputs.has(bundle.notice), false, `duplicate OpenCode V2 notice output: ${bundle.notice}`);
      producedOutputs.add(bundle.notice);
      compareOrWrite(bundle.notice, Buffer.from(renderNotice(names)), check);
    }
  }
  assert.deepEqual([...producedOutputs].sort(), artifactManifest.outputs, 'bundle producer manifest does not match outputs');
  // npm pack --json reserves stdout for its machine-readable manifest, even
  // while lifecycle scripts run. Keep this useful build diagnostic separate.
  console.error(`${check ? 'ok' : 'built'} OpenCode V2 bundles (${BUNDLES.length} entries)`);
}
if (require.main === module) main().catch((error) => { console.error(error.message); process.exitCode = 1; });
module.exports = { BUNDLE_PRODUCER, getBundleArtifactManifest, main };
